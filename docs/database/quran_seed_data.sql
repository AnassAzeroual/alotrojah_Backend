DELIMITER //
CREATE PROCEDURE `seed_calendar`()
BEGIN
  DECLARE n INT DEFAULT 1; DECLARE tno INT; DECLARE tid BIGINT; DECLARE d DATE; DECLARE wt VARCHAR(10);
  WHILE n <= 42 DO
    SET tno = CASE WHEN n BETWEEN 1 AND 7 THEN 1 WHEN n BETWEEN 8 AND 14 THEN 2
      WHEN n BETWEEN 15 AND 21 THEN 3 WHEN n BETWEEN 22 AND 28 THEN 4
      WHEN n BETWEEN 29 AND 35 THEN 5 ELSE 6 END;
    SELECT `id` INTO tid FROM `terms` WHERE `season_id`=1 AND `term_number`=tno;
    SET wt = IF(MOD(n,7)=0,'review','study');
    SET d = DATE_ADD('2025-09-01', INTERVAL (n-1)*7 DAY);
    INSERT INTO `weeks` (`id`,`season_id`,`term_id`,`week_number_global`,`week_number_in_term`,`week_type`,`start_date`,`end_date`)
    VALUES (n,1,tid,n,n,wt,d,DATE_ADD(d, INTERVAL 6 DAY));
    SET n = n + 1;
  END WHILE;
END //
DELIMITER ;
CALL `seed_calendar`();
DROP PROCEDURE IF EXISTS `seed_calendar`;

DELIMITER //
CREATE PROCEDURE `seed_sessions`()
BEGIN
  DECLARE s INT DEFAULT 1; DECLARE w INT; DECLARE k INT; DECLARE tid BIGINT; DECLARE d DATE; DECLARE st VARCHAR(15);
  WHILE s <= 126 DO
    SET w = CEIL(s/3); SET k = ((s-1) MOD 3) + 1;
    SELECT `term_id`,`start_date`,`week_type` INTO tid,d,@ww FROM `weeks` WHERE `id`=w;
    SET st = IF(@ww='review', IF(k<3,'revision','exam'), 'memorization');
    INSERT INTO `sessions` (`id`,`season_id`,`term_id`,`week_id`,`session_number_global`,`session_number_in_week`,`session_type`,`planned_date`,`status`)
    VALUES (s,1,tid,w,s,k,st,DATE_ADD(d, INTERVAL (k-1) DAY), IF(s<=6,'done','planned'));
    SET s = s + 1;
  END WHILE;
END //
DELIMITER ;
CALL `seed_sessions`();
DROP PROCEDURE IF EXISTS `seed_sessions`;

